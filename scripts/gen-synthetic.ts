/** Generate the SYNTHETIC demo team: 20 fictional members, six closed sprints.
 *
 * Writes data/demo/dataset.json in the same shape as the local store. Member
 * identities exist only inside this script (to give answers a realistic
 * person-to-person spread) and are not written out: the file holds anonymous
 * responses in shuffled order, exactly what the store would hold. Notes are not
 * included; the demo's themes come from pipeline runs over data/synthetic/notes.json.
 *
 *   npm run synth
 */

import { writeFileSync } from "node:fs";

import type { Dataset } from "../lib/release";
import type { CheckinResponse, Dimension, Score, Sprint } from "../lib/types";

const SEED = 20261102;
const K = 5;

function mulberry32(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rand = mulberry32(SEED);
const normal = () => Math.sqrt(-2 * Math.log(1 - rand())) * Math.cos(2 * Math.PI * rand());
const shuffle = <T>(xs: T[]) => {
  for (let i = xs.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [xs[i], xs[j]] = [xs[j], xs[i]];
  }
  return xs;
};

const dimensions: Dimension[] = [
  { id: "subteam", label: "Sub-team", values: ["Payments", "Platform"] },
  { id: "role", label: "Role", values: ["Developer", "QA", "Design", "Product"] },
];

const roster: { subteam: string; role: string }[] = [
  ...Array.from({ length: 7 }, () => ({ subteam: "Payments", role: "Developer" })),
  ...Array.from({ length: 2 }, () => ({ subteam: "Payments", role: "QA" })),
  { subteam: "Payments", role: "Design" },
  { subteam: "Payments", role: "Product" },
  ...Array.from({ length: 6 }, () => ({ subteam: "Platform", role: "Developer" })),
  ...Array.from({ length: 2 }, () => ({ subteam: "Platform", role: "QA" })),
  { subteam: "Platform", role: "Design" },
];
const members = roster.map((m) => ({ ...m, offset: { energy: 0.5 * normal(), workload: 0.5 * normal(), clarity: 0.4 * normal() } }));

// The storyline: an incident and meeting overload in Sprint 23, an action to protect
// Wednesday afternoons, unclear goals in Sprint 25, an action on sprint goals.
const plan = [
  { label: "Sprint 21", respondents: 16, energy: 3.6, workload: 3.4, clarity: 3.8, blocked: 0.15 },
  { label: "Sprint 22", respondents: 17, energy: 3.3, workload: 2.8, clarity: 3.3, blocked: 0.2 },
  { label: "Sprint 23", respondents: 17, energy: 2.5, workload: 2.2, clarity: 3.0, blocked: 0.4 },
  { label: "Sprint 24", respondents: 15, energy: 3.3, workload: 3.0, clarity: 3.4, blocked: 0.25 },
  { label: "Sprint 25", respondents: 18, energy: 3.3, workload: 3.2, clarity: 2.5, blocked: 0.35 },
  { label: "Sprint 26", respondents: 16, energy: 3.8, workload: 3.6, clarity: 3.9, blocked: 0.1 },
];

const toScore = (x: number) => Math.min(5, Math.max(1, Math.round(x))) as Score;

const sprints: Sprint[] = plan.map((p, i) => ({
  id: `s${i + 1}`,
  label: p.label,
  index: i + 1,
  status: "closed",
  frozen: { k: K, dimensions },
}));

const responses: CheckinResponse[] = [];
plan.forEach((p, i) => {
  for (const m of shuffle([...members]).slice(0, p.respondents)) {
    const attrs: Record<string, string> = {};
    if (rand() > 0.08) attrs.subteam = m.subteam;
    if (rand() > 0.08) attrs.role = m.role;
    responses.push({
      sprint: `s${i + 1}`,
      energy: toScore(p.energy + m.offset.energy + 0.7 * normal()),
      workload: toScore(p.workload + m.offset.workload + 0.7 * normal()),
      clarity: toScore(p.clarity + m.offset.clarity + 0.7 * normal()),
      blocked: rand() < p.blocked,
      attrs,
    });
  }
});

const dataset: Dataset & { _comment: string } = {
  _comment: `SYNTHETIC demo data generated by scripts/gen-synthetic.ts (seed ${SEED}). Fictional team; no real responses.`,
  k: K,
  dimensions,
  sprints,
  responses: shuffle(responses),
  actions: [
    { id: "a1", afterSprint: "s3", text: "Keep Wednesday afternoons free of meetings", metric: "energy" },
    { id: "a2", afterSprint: "s5", text: "Agree a one-line sprint goal with the product owner before planning", metric: "clarity" },
  ],
  themes: [],
  prompts: [],
};

writeFileSync("data/demo/dataset.json", `${JSON.stringify(dataset, null, 2)}\n`);
console.log(`wrote data/demo/dataset.json: ${responses.length} responses over ${sprints.length} sprints`);
